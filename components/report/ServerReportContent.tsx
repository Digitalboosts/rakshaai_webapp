import { TrustData } from "@/types/trust-data";
import ReactMarkdown from 'react-markdown';
import rehypeRaw from 'rehype-raw';
import rehypeSanitize from 'rehype-sanitize';

interface ServerReportContentProps {
  data: TrustData;
  analyzedUrl: string;
}

/**
 * Server component that renders SEO-friendly content for crawlers
 * This ensures Google and other search engines can index the report data
 */
export default function ServerReportContent({ data, analyzedUrl }: ServerReportContentProps) {
  const title = data
    ? `Security Analysis for ${data.url_details?.complete_domain || data.upi_id || data.phone_number || 'Website'}`
    : 'Security Analysis Report';

  return (
    <div className="seo-content">
      {/* Header Information for Crawlers */}
      <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8">
        <div className="glass rounded-2xl p-6 sm:p-8 border-2 border-indigo-100 dark:border-indigo-900/30 mb-8">
          <div className="flex items-start space-x-4 mb-4">
            <div className="w-12 h-12 sm:w-14 sm:h-14 rounded-xl flex items-center justify-center flex-shrink-0">
              <img
                src="/rakshaai-logo.svg"
                alt="RakshaAI Logo"
                width={56}
                height={56}
                className="w-full h-full"
              />
            </div>
            <div className="flex-1 min-w-0">
              <h1 className="text-xl sm:text-2xl lg:text-4xl font-bold text-gray-900 dark:text-white mb-2">
                {title}
              </h1>
              
              {/* Disclaimer for SEO */}
              <div className="mt-2 mb-4 p-3 rounded-lg bg-yellow-50 dark:bg-yellow-900/30 border border-yellow-200 dark:border-yellow-800 text-xs sm:text-sm text-yellow-900 dark:text-yellow-200 font-medium">
                <strong>Disclaimer:</strong> This report is generated by AI systems. AI-based analysis may occasionally be inaccurate. Always verify important information independently.
              </div>

              {/* Analyzing Information */}
              <div className="flex items-center flex-wrap gap-2 mb-4">
                <span className="text-xs sm:text-sm font-bold lg:text-base text-gray-600 dark:text-gray-400">
                  Analyzing:
                </span>
                <div className="flex items-center space-x-2 px-3 py-1.5 rounded-lg bg-indigo-50 dark:bg-indigo-900/20 border border-indigo-200 dark:border-indigo-800/40">
                  <span className="font-semibold text-gray-900 dark:text-white text-xs sm:text-sm lg:text-base">
                    {data.detected_type === 'upi' ? data.upi_id :
                      data.detected_type === 'phone' ? data.phone_number :
                        (analyzedUrl || data.url_details?.complete_domain)}
                  </span>
                </div>
              </div>

              {/* Summary for SEO */}
              {data.summary && (
                <div className="mt-2 flex items-start">
                  <span className="text-xs sm:text-sm lg:text-base font-semibold text-gray-900 dark:text-white mr-2">
                    Summary:
                  </span>
                  <div className="text-sm text-gray-700 dark:text-gray-300 leading-relaxed">
                    <ReactMarkdown
                      rehypePlugins={[rehypeRaw, rehypeSanitize]}
                      components={{ p: ({ node, ...props }) => <span {...props} /> }}
                    >
                      {data.summary}
                    </ReactMarkdown>
                  </div>
                </div>
              )}
            </div>
          </div>
        </div>

        {/* Trust Score - SEO Friendly */}
        <div className="glass rounded-2xl p-6 mb-8 border border-gray-200 dark:border-gray-800">
          <h2 className="text-2xl font-bold text-gray-900 dark:text-white mb-4">Trust Score</h2>
          <div className="text-4xl font-bold text-indigo-600 dark:text-indigo-400 mb-2">
            {data.trust_percentage}%
          </div>
          <p className="text-gray-600 dark:text-gray-400">
            Based on {data.total_number_of_reviews} reviews and analysis
          </p>
        </div>

        {/* Domain Information for SEO */}
        {data.domain_info && data.detected_type !== 'upi' && data.detected_type !== 'phone' && (
          <div className="glass rounded-2xl p-6 mb-8 border border-gray-200 dark:border-gray-800">
            <h2 className="text-2xl font-bold text-gray-900 dark:text-white mb-4">Domain Information</h2>
            <dl className="space-y-3">
              {data.domain_info.domain && (
                <div>
                  <dt className="font-semibold text-gray-700 dark:text-gray-300">Domain:</dt>
                  <dd className="text-gray-900 dark:text-white">{data.domain_info.domain}</dd>
                </div>
              )}
              {data.domain_info.domain_age_days && (
                <div>
                  <dt className="font-semibold text-gray-700 dark:text-gray-300">Domain Age:</dt>
                  <dd className="text-gray-900 dark:text-white">{data.domain_info.domain_age_days} days</dd>
                </div>
              )}
              {data.domain_info.registrar && (
                <div>
                  <dt className="font-semibold text-gray-700 dark:text-gray-300">Registrar:</dt>
                  <dd className="text-gray-900 dark:text-white">{data.domain_info.registrar}</dd>
                </div>
              )}
              {data.domain_info.ip && (
                <div>
                  <dt className="font-semibold text-gray-700 dark:text-gray-300">IP Address:</dt>
                  <dd className="text-gray-900 dark:text-white">{data.domain_info.ip}</dd>
                </div>
              )}
            </dl>
          </div>
        )}

        {/* SSL Information for SEO */}
        {data.ssl_info && data.detected_type !== 'upi' && data.detected_type !== 'phone' && (
          <div className="glass rounded-2xl p-6 mb-8 border border-gray-200 dark:border-gray-800">
            <h2 className="text-2xl font-bold text-gray-900 dark:text-white mb-4">SSL Certificate</h2>
            <dl className="space-y-3">
              <div>
                <dt className="font-semibold text-gray-700 dark:text-gray-300">Status:</dt>
                <dd className="text-gray-900 dark:text-white">
                  {data.ssl_info.valid ? 'Valid & Secure ✓' : 'Invalid ✗'}
                </dd>
              </div>
              {data.ssl_info.issuer?.commonName && (
                <div>
                  <dt className="font-semibold text-gray-700 dark:text-gray-300">Issuer:</dt>
                  <dd className="text-gray-900 dark:text-white">{data.ssl_info.issuer.commonName}</dd>
                </div>
              )}
              {data.ssl_info.days_left !== undefined && (
                <div>
                  <dt className="font-semibold text-gray-700 dark:text-gray-300">Days Until Expiry:</dt>
                  <dd className="text-gray-900 dark:text-white">{data.ssl_info.days_left} days</dd>
                </div>
              )}
            </dl>
          </div>
        )}

        {/* Reviews for SEO */}
        {data.related_scam_reports && data.related_scam_reports.length > 0 && (
          <div className="glass rounded-2xl p-6 mb-8 border border-gray-200 dark:border-gray-800">
            <h2 className="text-2xl font-bold text-gray-900 dark:text-white mb-4">
              Related Reports ({data.related_scam_reports.length})
            </h2>
            <div className="space-y-4">
              {data.related_scam_reports.slice(0, 5).map((report) => (
                <div key={report.id} className="border-b border-gray-200 dark:border-gray-700 pb-4 last:border-0">
                  <div className="font-semibold text-gray-900 dark:text-white mb-1">
                    {report.name}
                  </div>
                  <div className="text-sm text-gray-700 dark:text-gray-300">
                    {report.review}
                  </div>
                  {report.created_at && (
                    <div className="text-xs text-gray-500 dark:text-gray-400 mt-1">
                      {new Date(report.created_at).toLocaleDateString()}
                    </div>
                  )}
                </div>
              ))}
            </div>
          </div>
        )}

        {/* Action Items for SEO */}
        {data.action_items && (
          <div className="glass rounded-2xl p-6 mb-8 border border-gray-200 dark:border-gray-800">
            <h2 className="text-2xl font-bold text-gray-900 dark:text-white mb-4">Recommended Actions</h2>
            <div className="space-y-4">
              {data.action_items.risk_level && (
                <div>
                  <h3 className="font-semibold text-gray-900 dark:text-white mb-2">Risk Level</h3>
                  <p className="text-gray-700 dark:text-gray-300">{data.action_items.risk_level}</p>
                </div>
              )}
              {data.action_items.can_do && data.action_items.can_do.length > 0 && (
                <div>
                  <h3 className="font-semibold text-gray-900 dark:text-white mb-2">You Can Do</h3>
                  <ul className="space-y-1 list-disc list-inside">
                    {data.action_items.can_do.map((item, index) => (
                      <li key={index} className="text-gray-700 dark:text-gray-300">{item}</li>
                    ))}
                  </ul>
                </div>
              )}
              {data.action_items.should_avoid && data.action_items.should_avoid.length > 0 && (
                <div>
                  <h3 className="font-semibold text-gray-900 dark:text-white mb-2">You Should Avoid</h3>
                  <ul className="space-y-1 list-disc list-inside">
                    {data.action_items.should_avoid.map((item, index) => (
                      <li key={index} className="text-gray-700 dark:text-gray-300">{item}</li>
                    ))}
                  </ul>
                </div>
              )}
              {data.action_items.payment_advice && (
                <div>
                  <h3 className="font-semibold text-gray-900 dark:text-white mb-2">Payment Advice</h3>
                  <p className="text-gray-700 dark:text-gray-300">{data.action_items.payment_advice}</p>
                </div>
              )}
            </div>
          </div>
        )}
      </div>
    </div>
  );
}
