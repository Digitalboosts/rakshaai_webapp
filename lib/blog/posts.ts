export function getRelatedPosts(currentSlug: string, limit = 3): BlogPost[] {
    const current = blogPosts.find((p) => p.slug === currentSlug)
    if (!current) return blogPosts.filter((p) => p.slug !== currentSlug).slice(0, limit)

    // Prefer same-cluster posts first, then fill with others
    const sameCluster = blogPosts.filter((p) => p.slug !== currentSlug && p.cluster === current.cluster)
    const otherPosts = blogPosts.filter((p) => p.slug !== currentSlug && p.cluster !== current.cluster)
    return [...sameCluster, ...otherPosts].slice(0, limit)
}
